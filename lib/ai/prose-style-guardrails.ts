  "输出前自检：如果同一章或同一精修段落里出现多处“不是/而是”“不是/是”的二元对照表达，先把它们改成动作、场景细节、人物反应、台词或因果推进，再输出正文。",
  "把抽象判断改成具体动作、场景细节、人物反应和因果推进，不要用排比式总结替代叙事。",
  "句式要有长短变化，减少“他意识到/他明白/真正的问题在于”这类解释腔，让读者从事件本身看出含义。",
